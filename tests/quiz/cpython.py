"""Решение квиза по CPython и PyPy."""

# ## Введение в Python и CPython
#
# **1. Что такое CPython и чем он отличается от Python?**
#
# Python — язык программирования с определёнными синтаксисом и семантикой.
# CPython — его основная, наиболее распространённая реализация: программа,
# которая выполняет код на Python. Ядро CPython написано на C.
#
# **2. Ответьте на вопрос с изображения в задании.**
#
# На изображении сравниваются язык Python и его реализация CPython:
#
# | Аспект | Python | CPython |
# | --- | --- | --- |
# | Определение | Язык высокого уровня | Основная реализация Python |
# | Исполнение | Правила языка | Компиляция в байт-код и его выполнение |
# | Реализация | Не фиксирует язык реализации | Ядро написано на C |
# | Примеры | Задаёт `for`, `if`, функции | Выполняет такой код |
#
# CPython компилирует исходный Python-код в байт-код, который выполняет
# его виртуальная машина. Поэтому `for` и `if` — конструкции языка Python,
# а CPython обеспечивает их выполнение. При этом не весь проект написан
# на C: значительная часть стандартной библиотеки написана на Python.
#
# **3. Сколько существует реализаций Python и какая самая популярная?**
#
# Фиксированного числа нет: реализации появляются и развиваются.
# Примеры: CPython, PyPy, Jython, IronPython, MicroPython и GraalPy.
# Это не полный список. Самая распространённая реализация — CPython.
#
# **4. На каком языке написан CPython?**
#
# Ядро интерпретатора написано на C. Значительная часть стандартной
# библиотеки написана на самом Python.
#
# ## Поиск и установка CPython
#
# **5. (Опционально) Кто создал CPython?**
#
# Гвидо ван Россум (Guido van Rossum).
#
# **6. Почему Python считается быстрым, несмотря на то, что это
# интерпретируемый язык?**
#
# Нужно различать скорость разработки и скорость выполнения программы.
# Python удобен для быстрой разработки, но обычные циклы в CPython часто
# медленнее аналогичного кода на C. Встроенные операции и библиотеки могут
# выполнять основную работу в оптимизированном нативном коде. Поэтому
# скорость зависит от задачи и используемых библиотек.
#
# **7. Укажите путь к интерпретатору CPython на вашем компьютере.**
#
# В исходном ответе указан путь `~/miniconda3/bin/python3`.
# Это путь к базовому окружению Miniconda; у окружения `ds-course` свой
# интерпретатор. Его точный путь нужно проверять в активном окружении:
#
# ```bash
# conda activate ds-course
