# ```
#
# ## Структура CPython
#
# **8. Что содержится в папке include в CPython?**
#
# В дереве исходников каталог называется `Include`. Он содержит
# заголовочные файлы C (`.h`): публичный C API, детали API CPython
# и внутренние заголовки. Это не то же самое, что исходники `.c`.
# В установленном Python путь к заголовкам зависит от сборки и окружения;
# его можно получить через `sysconfig.get_path("include")`.
#
# **9. Где найти исходный код CPython?**
#
# https://github.com/python/cpython
#
# **10. (Опционально) Как работает CPython при выполнении кода?**
#
# CPython разбирает исходный код и компилирует его в промежуточный
# байт-код. Затем байт-код выполняет виртуальная машина Python (PVM),
# то есть интерпретатор байт-кода внутри CPython. Это не машинные
# инструкции, которые процессор исполняет напрямую.
#
# ## Запуск файла с помощью CPython
#
# **11. Какая команда используется для запуска файла через CPython?**
#
# `python example.py` или `python3 example.py`, если выбранная команда
# указывает на CPython. Команда без имени файла открывает интерактивный
# интерпретатор. Проверка реализации:
#
# ```bash
# python -c "import platform; print(platform.python_implementation())"
# ```
#
# **12. Можно ли запускать текстовые файлы через интерпретатор Python?**
#
# Да, например `python example.txt`, если файл содержит корректный код
# Python. При явном запуске через интерпретатор расширение файла
# не определяет язык; содержимое должно быть кодом Python.
#
# **13. Как указать путь к интерпретатору и файлу для выполнения кода?**
#
# Сначала указывают исполняемый файл интерпретатора, затем файл программы.
# Пути с пробелами заключают в кавычки. Пример для Linux:
#
# ```bash
# "/path/to/python" "/path/to/example.py"
# ```
#
# ## Введение в PyPy
#
# **14. Чем PyPy отличается от CPython?**
#
# PyPy — другая реализация Python; её интерпретатор написан на RPython,
# ограниченном подмножестве Python. В обычной сборке PyPy есть
# JIT-компилятор (Just-In-Time): во время работы он переводит часто
# выполняемые участки кода в машинные инструкции.
# CPython 3.11 выполняет байт-код специализирующим интерпретатором без JIT.
# Утверждение «в CPython никогда нет JIT» неверно: в новых версиях
# доступны сборки с экспериментальным JIT.
#
# **15. Почему PyPy подходит не для всех проектов на Python?**
#
# Нужно учитывать поддерживаемую версию Python и совместимость зависимостей.
# Расширения, использующие C API CPython, могут требовать отдельной сборки
# для PyPy и работать с накладными расходами. Для коротких программ
# прогрев JIT может не окупиться, а код внутри нативных библиотек JIT
# PyPy обычно не ускоряет. Совместимость и скорость проверяют на проекте.
#
# **16. Где можно скачать PyPy?**
#
# https://www.pypy.org/download.html
#
# ## Установка и запуск PyPy
#
# **17. Как установить PyPy после скачивания?**
#
# Скачать сборку под свою ОС и архитектуру, распаковать архив целиком
# и запустить интерпретатор из него. В Linux исполняемый файл находится
# в каталоге `bin`; его точное имя зависит от сборки. Можно добавить этот
# каталог в `PATH` или создать символическую ссылку. Переносить только
# исполняемый файл нельзя: ему нужны библиотеки из распакованного архива.
#
# **18. Как запустить файл с помощью PyPy?**
#
# `pypy3 example_pypy.py`, если команда `pypy3` доступна в `PATH`.
# Иначе нужно указать фактический путь к исполняемому файлу PyPy.
# Имя `pypy3.12` подходит только для сборки с таким именем файла.
#
# **19. Почему PyPy может выполнять код быстрее CPython?**
#
# JIT компилирует и оптимизирует часто выполняемые участки кода, сокращая
# затраты на интерпретацию. Это может ускорять вычислительные циклы
# на чистом Python. Ускорение не гарантировано для любой программы:
# оно зависит от задачи, прогрева JIT, версии и используемых библиотек.
