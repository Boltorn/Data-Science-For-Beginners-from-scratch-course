# `sys.base_prefix + '/include'` может содержать заголовки других библиотек
# и не совпадать с каталогом заголовков текущего Python.
# Поэтому число 163 нельзя считать подтверждённым числом файлов CPython.
#
# Для проверки именно заголовков текущего интерпретатора:
#
# ```python
# import sysconfig
# from pathlib import Path
#
# include_dir = Path(sysconfig.get_path("include"))
# print("Include:", include_dir)
# print("Headers (*.h):", sum(p.is_file() for p in include_dir.glob("*.h")))
# ```
#
# Команда считает файлы `.h` только в выбранном каталоге, без подкаталогов.
# Для рекурсивного подсчёта нужна `rglob("*.h")`; это уже другой подсчёт.
