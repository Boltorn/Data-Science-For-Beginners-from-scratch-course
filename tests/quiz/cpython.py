# ### Задание 5. Сравнение производительности CPython и PyPy
#
# Код `performance_test.py` из задания сохранён с исходным таймером,
# чтобы записанные ниже результаты относились к тому же примеру:
#
# ```python
# import time
#
# start_time = time.time()
# total = 0
# for i in range(1, 10_000_000):
#     total += i
# end_time = time.time()
#
# print("Result:", total)
# print("Execution time:", end_time - start_time, "seconds")
# ```
#
# Команды запуска:
#
# ```bash
# python performance_test.py
# pypy3 performance_test.py
# ```
#
# Исходные результаты из PR (по одному замеру для каждого интерпретатора):
#
# | Интерпретатор | Result | Время, с |
# | --- | --- | --- |
# | CPython (`python3`) | 49999995000000 | 0.7251119613647461 |
# | PyPy (`pypy3`) | 49999995000000 | 0.10695767402648926 |
#
# `range(1, 10_000_000)` не включает 10 000 000. Проверка суммы:
# `9_999_999 * 10_000_000 // 2 = 49_999_995_000_000`.
# Оба записанных результата верны.
#
# Отношение времён: `0.7251119613647461 / 0.10695767402648926`,
# то есть примерно **6,78 раза** (округлённо — 7 раз) в этом запуске.
# Такой результат согласуется с оптимизацией цикла JIT-компилятором PyPy,
# но один замер не доказывает, что PyPy всегда быстрее в семь раз.
#
# Для исходных замеров не сохранены полные версии интерпретаторов,
# характеристики машины, нагрузка и повторные запуски. Их точное время
# нельзя воспроизвести только по этим двум числам.
# Таймер охватывает цикл, но не запуск процесса. Время прогрева JIT
# внутри цикла включено; отдельного прогрева перед замером нет.
#
# Для повторной проверки нужно сохранить вывод `python --version`
# и `pypy3 --version`, модель CPU и ОС, выполнить один и тот же файл
# минимум три раза каждым интерпретатором на одной машине и сравнить
# медианы. Запуски из новых процессов включают прогрев JIT каждый раз.
# Измерение уже прогретого кода внутри одного процесса — отдельный опыт.
# Для новых измерений длительности предпочтителен `time.perf_counter()`;
# после смены таймера времена нужно измерить заново для обоих вариантов.
